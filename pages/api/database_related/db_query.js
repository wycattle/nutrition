// pages/api/database_related/db_query.js
import { Pool } from 'pg';
import { recalcAffectedRecipes } from '../../../lib/recalcAffectedRecipes';

const pool = new Pool({
  connectionString: process.env.DATABASE_URL, // Set your Neon connection string in .env
  ssl: { rejectUnauthorized: false },
});

export default async function handler(req, res) {
  if (req.method !== 'POST') {
    res.setHeader('Allow', ['POST']);
    return res.status(405).end(`Method ${req.method} Not Allowed`);
  }

  const { query, action, row } = req.body;

  // If raw SQL query provided, run it
  if (query) {
    try {
      const result = await pool.query(query);
      return res.status(200).json(result.rows);
    } catch (error) {
      console.error('DB error:', error);
      return res.status(500).json({ error: error.message });
    }
  }

  // Action-based API for user_nutrition table
  if (!action || !row) {
    return res.status(400).json({ error: 'No action or row provided' });
  }

  // Only allow these columns for safety
  const allowedCols = [
    'id', 'user_id', 'desc1', 'desc2', 'portion', 'calories', 'carb', 'fat', 'protein', 'fiber', 'gi', 'note',
    // lipids & minerals
    'omega3', 'omega6', 'cholesterol_mg', 'sodium_mg', 'potassium_mg', 'calcium_mg', 'iron_mg',
    'magnesium_mg', 'iodine_mcg', 'manganese_mg', 'selenium_mcg', 'zinc_mg',
    // vitamins
    'vit_a_mcg', 'vit_b1_mg', 'vit_b2_mg', 'vit_b3_mg', 'vit_b5_mg', 'vit_b6_mg', 'vit_b12_mcg',
    'biotin_mcg', 'choline_mg', 'folate_mcg', 'vit_c_mg', 'vit_d_mcg', 'vit_e_mg', 'vit_k_mcg',
  ];
  const table = 'user_nutrition';
  // Text columns that should keep empty strings as-is; everything else is numeric → coerce '' to null
  const textCols = new Set(['user_id', 'desc1', 'desc2', 'note']);
  const coerce = (col, val) => (!textCols.has(col) && val === '') ? null : val;

  try {
    if (action === 'insert') {
      // Remove id if present (should be generated by DB)
      const insertRow = { ...row };
      delete insertRow.id;
      const cols = Object.keys(insertRow).filter(c => allowedCols.includes(c));
      const vals = cols.map(c => coerce(c, insertRow[c]));
      const placeholders = cols.map((_, i) => `$${i + 1}`).join(', ');
      const sql = `INSERT INTO ${table} (${cols.join(', ')}) VALUES (${placeholders}) RETURNING *`;
      const result = await pool.query(sql, vals);
      // Recalc any recipes that use this ingredient
      if (insertRow.user_id && insertRow.desc1 && insertRow.desc2) {
        await recalcAffectedRecipes(pool, insertRow.user_id, insertRow.desc1, insertRow.desc2).catch(e => console.error('recalcAffectedRecipes error:', e));
      }
      return res.status(200).json(result.rows);
    } else if (action === 'update') {
      if (!row.id) return res.status(400).json({ error: 'Missing id for update' });
      const updateCols = Object.keys(row).filter(c => allowedCols.includes(c) && c !== 'id');
      const setClause = updateCols.map((c, i) => `${c} = $${i + 1}`).join(', ');
      const vals = updateCols.map(c => coerce(c, row[c]));
      vals.push(row.id);
      const sql = `UPDATE ${table} SET ${setClause} WHERE id = $${vals.length} RETURNING *`;
      const result = await pool.query(sql, vals);
      // Recalc any recipes that use this ingredient
      if (row.user_id && row.desc1 && row.desc2) {
        await recalcAffectedRecipes(pool, row.user_id, row.desc1, row.desc2).catch(e => console.error('recalcAffectedRecipes error:', e));
      }
      return res.status(200).json(result.rows);
    } else if (action === 'delete') {
      if (!row.id) return res.status(400).json({ error: 'Missing id for delete' });
      const sql = `DELETE FROM ${table} WHERE id = $1 RETURNING *`;
      const result = await pool.query(sql, [row.id]);
      // Recalc any recipes that use this ingredient (using stored desc1/desc2 before deletion)
      if (row.user_id && row.desc1 && row.desc2) {
        await recalcAffectedRecipes(pool, row.user_id, row.desc1, row.desc2).catch(e => console.error('recalcAffectedRecipes error:', e));
      }
      return res.status(200).json(result.rows);
    } else {
      return res.status(400).json({ error: 'Unknown action' });
    }
  } catch (error) {
    console.error('DB error:', error);
    return res.status(500).json({ error: error.message });
  }
}
